// from a GitHub Pages project subpath or loaded as a local file inside the
// Capacitor Android WebView.
export default defineConfig({
  base: "./",
  plugins: [react(), tailwindcss(), viteSingleFile()],
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "src"),
    },
  },
});
